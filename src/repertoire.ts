/** The repertoire's name in the current language. */
export const repName = (r: Repertoire) => (getLang() === 'en' && EN[r.id]?.name) || r.name;

/** A line's name, idea and notes in the current language (Hebrew when a translation is missing). */
export function lineText(r: Repertoire, l: Line) {
  const en = getLang() === 'en' ? EN[r.id]?.lines[l.name] : undefined;
  return { name: en?.name ?? l.name, idea: en?.idea ?? l.idea, notes: en?.notes ?? l.notes ?? {} };
}

/** Position key: board, side, castling, en-passant (ignores move counters). */
export const posKey = (fen: string) => fen.split(' ').slice(0, 4).join(' ');

/** "2.Bf4" for White's move at ply 2, "4...Qb6" for Black's at ply 7 (ply counted from 0). */
export const moveLabel = (ply: number, san: string) =>
  ply % 2 === 0 ? `${ply / 2 + 1}.${san}` : `${(ply - 1) / 2 + 1}...${san}`;

/** The line's moves with the position before and after each one. */
export function lineMoves(moves: string): Move[] {
  const c = new Chess();
  return moves.split(/\s+/).map((san) => c.move(san));
}

export type Book = Map<string, string[]>; // posKey -> SAN moves seen in repertoire

export function buildBook(rep: Repertoire): Book {
  const book: Book = new Map();
  for (const line of rep.lines) {
    const c = new Chess();
    for (const san of line.moves.split(/\s+/)) {
      const key = posKey(c.fen());
      const m = c.move(san); // throws on an illegal line -> caught by the check script
      const list = book.get(key) ?? [];
      if (!list.includes(m.san)) list.push(m.san);
      book.set(key, list);
    }
  }
  return book;
}
