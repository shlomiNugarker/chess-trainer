const SAN = String.raw`(?:\d+\.{1,3}|\.{3})?(?:O-O(?:-O)?|[KQRBN]?[a-h]?[1-8]?x?[a-h][1-8](?:=[QRBN])?)[+#]?(?![A-Za-z0-9])`;
const MOVES = new RegExp(`${SAN}(?:[ /-]{1,3}${SAN})*`, 'g');

/**
 * Moves inside a right-to-left text, isolated as left-to-right: otherwise the neutral characters at their ends jump to
 * the other side ("1.e4" shows as "e4.1", "...d5" as "d5...", "Qa4+" as "+Qa4").
 */
export const isolateMoves = (text: string) => text.replace(MOVES, (m) => (/[.+#]/.test(m) ? `\u2066${m}\u2069` : m));

/** The repertoire's name in the current language. */
export function repName(r: Repertoire) {
  const name = explanations()?.[r.id]?.name ?? r.name;
  return dir() === 'rtl' ? isolateMoves(name) : name;
}

/** A line's name, idea and notes in the current language (English where it has none, see hasExplanations). */
export function lineText(r: Repertoire, l: Line): LineText {
  if (l.custom) {
    return {
      name: tr(msg`★ Vs ${l.custom}`),
      idea: tr(msg`A branch you added from your games: opponents played ${l.custom} against you, and this is Stockfish's answer.`),
      notes: {},
    };
  }
  const translated = explanations()?.[r.id]?.lines[l.id];
  if (!translated) return { name: l.name, idea: l.idea ?? '', notes: l.notes ?? {} };
  return dir() === 'rtl' ? isolated(translated) : translated;
}

const isolatedTexts = new WeakMap<LineText, LineText>();
function isolated(t: LineText): LineText {
  let x = isolatedTexts.get(t);
  if (!x) {
    const notes = Object.fromEntries(Object.entries(t.notes).map(([k, v]) => [k, isolateMoves(v)]));
    isolatedTexts.set(t, (x = { name: isolateMoves(t.name), idea: isolateMoves(t.idea), notes }));
  }
  return x;
}

/** Shown in languages that have only the interface translated. */
export const explanationsNote = () =>
  tr('The explanations of the openings are in English. Moves use the English letters: K king, Q queen, R rook, B bishop, N knight.');

/** Position key: board, side, castling, en-passant (ignores move counters). */
export const posKey = (fen: string) => fen.split(' ').slice(0, 4).join(' ');

/** "2.Bf4" for White's move at ply 2, "4...Qb6" for Black's at ply 7 (ply counted from 0). */
export const moveLabel = (ply: number, san: string) =>
  ply % 2 === 0 ? `${ply / 2 + 1}.${san}` : `${(ply - 1) / 2 + 1}...${san}`;

/** The line's moves with the position before and after each one. */
export function lineMoves(moves: string): Move[] {
  const c = new Chess();
  return moves.split(/\s+/).map((san) => c.move(san));
}

const movesCache = new WeakMap<Line, Move[]>();
export const movesOf = (l: Line) => {
  let m = movesCache.get(l);
  if (!m) movesCache.set(l, (m = lineMoves(l.moves)));
  return m;
};

/**
 * Where a game stands in the repertoire: the lines it is in, and for each, the index in that line of the game's
 * last move. Found by the exact move order first, else by the position (a transposition).
 */
function placeInLines(rep: Repertoire, sans: string[]): { line: Line; at: number }[] {
  if (!sans.length) return [];
  const exact = rep.lines
    .filter((l) => {
      const ms = movesOf(l);
      return sans.length <= ms.length && sans.every((s, i) => ms[i].san === s);
    })
    .map((line) => ({ line, at: sans.length - 1 }));
  if (exact.length) return exact;
  const c = new Chess();
  for (const s of sans) c.move(s);
  const here = posKey(c.fen());
  const last = sans[sans.length - 1];
  return rep.lines.flatMap((line) => {
    const at = movesOf(line).findIndex((m) => m.san === last && posKey(m.after) === here);
    return at >= 0 ? [{ line, at }] : [];
  });
}

/**
 * For the training screen: the name of the line the game is in (and how many other lines share this position),
 * and the notes on the last two moves (the user's and the reply), in the current language.
 */
export function lineInfo(rep: Repertoire, sans: string[]) {
  const places = placeInLines(rep, sans);
  if (!places.length) return null;
  const notes: { label: string; text: string }[] = [];
  for (const back of [1, 0]) {
    if (sans.length - 1 - back < 0) continue;
    for (const { line, at } of places) {
      const i = at - back;
      if (i < 0) continue;
      const label = moveLabel(i, movesOf(line)[i].san);
      const text = lineText(rep, line).notes[label];
      if (text) {
        notes.push({ label, text });
        break;
      }
    }
  }
  return { name: lineText(rep, places[0].line).name, others: places.length - 1, notes };
}

/** The note explaining `nextSan` as the move to play after `sans` (for the "you left the line" card). */
export function noteForNext(rep: Repertoire, sans: string[], nextSan: string): string | undefined {
  const places = sans.length ? placeInLines(rep, sans) : rep.lines.map((line) => ({ line, at: -1 }));
  for (const { line, at } of places) {
    const m = movesOf(line)[at + 1];
    if (m?.san === nextSan) {
      const text = lineText(rep, line).notes[moveLabel(at + 1, m.san)];
      if (text) return text;
    }
  }
  return undefined;
}

export type Book = Map<string, string[]>; // posKey -> SAN moves seen in repertoire

export function buildBook(rep: Repertoire): Book {
  const book: Book = new Map();
  for (const line of rep.lines) {
    const c = new Chess();
    for (const san of line.moves.split(/\s+/)) {
      const key = posKey(c.fen());
      const m = c.move(san); // throws on an illegal line -> caught by the check script
      const list = book.get(key) ?? [];
      if (!list.includes(m.san)) list.push(m.san);
      book.set(key, list);
    }
  }
  return book;
}
